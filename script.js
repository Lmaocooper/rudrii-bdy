// OPENING: physical foil/parchment reveal
let taps=0;
const foil=$('#foilPaper');
foil.addEventListener('click',()=>{
  taps++;
  foil.classList.remove('tap1','tap2','tap3');
  foil.classList.add('tap'+Math.min(taps,3));
  if(taps===1) $('#tapNote').textContent='again…';
  if(taps===2) $('#tapNote').textContent='one more…';
  if(taps>=3){
    $('#opening').classList.add('revealed');
    $('#tapNote').textContent='';
    setTimeout(()=>$('#birthdayReveal').classList.add('show'),350);
  }
});

// CODE KEYPAD — generated by JS, so it works as real buttons
const keys=['1','2','3','4','5','6','7','8','9','⌫','0','↵'];
const keypad=$('#keypad');
keys.forEach(k=>{const b=document.createElement('button');b.type='button';b.dataset.key=k;b.textContent=k;keypad.appendChild(b);});
let code='';
function paintDots(){ $$('#dots i').forEach((d,i)=>d.classList.toggle('filled',i<code.length)); }
keypad.addEventListener('click',e=>{
  const b=e.target.closest('button'); if(!b)return;
  const k=b.dataset.key;
  if(k==='⌫') code=code.slice(0,-1);
  else if(k==='↵'){
    if(code==='0210'){
      $('#codeMsg').textContent='unlocked ♥';
      setTimeout(()=>go('record'),450);
    }else{
      $('#codeMsg').textContent='not quite… try again.';
      keypad.classList.remove('shake'); void keypad.offsetWidth; keypad.classList.add('shake');
      code='';
    }
  }else if(code.length<4) code+=k;
  paintDots();
});

