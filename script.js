const $ = (s, root=document) => root.querySelector(s);
const $$ = (s, root=document) => [...root.querySelectorAll(s)];
const chapters = $$('.chapter');
function go(id){ chapters.forEach(c=>c.classList.toggle('active',c.id===id)); localStorage.setItem('rudriChapter',id); window.scrollTo({top:0,behavior:'smooth'}); }
